#ifndef LORA_TRANSPORT_H
#define LORA_TRANSPORT_H

#include <stdint.h>

/**
 ******************************************************************************
  @功能：初始化 LoRa 应用数据传输层
  @日期：2026-08-19
  @参数：无
  @返回值：无
  @使用说明：在 LoRa AT 配置开始前调用；初始化后默认处于配置接收模式
 ******************************************************************************
 */
void LoraTransport_Init(void);

/**
 ******************************************************************************
  @功能：切换到 LoRa 二进制应用数据接收模式
  @日期：2026-08-19
  @参数：无
  @返回值：无
  @使用说明：只有 LoRa 模块完成 AT 配置并重启成功后才能调用
 ******************************************************************************
 */
void LoraTransport_EnableApplicationMode(void);

/**
 ******************************************************************************
  @功能：查询 USART2 当前是否接收二进制应用数据
  @日期：2026-08-19
  @参数：无
  @返回值：uint8_t - 1 表示应用模式，0 表示 AT 配置模式
 ******************************************************************************
 */
uint8_t LoraTransport_IsApplicationMode(void);

/**
 ******************************************************************************
  @功能：由 USART2 中断写入一个 LoRa 应用数据字节
  @日期：2026-08-19
  @参数：[输入] byte - 接收到的字节
  @返回值：uint8_t - 1 表示写入成功，0 表示尚未进入应用模式或缓冲区已满
  @线程安全：仅供 USART2 接收中断调用
 ******************************************************************************
 */
uint8_t LoraTransport_PushRxFromIsr(uint8_t byte);

/**
 ******************************************************************************
  @功能：记录一次 USART2 接收硬件错误
  @日期：2026-08-19
  @参数：无
  @返回值：无
  @线程安全：仅供 USART2 错误回调调用
 ******************************************************************************
 */
void LoraTransport_ReportRxErrorFromIsr(void);

/**
 ******************************************************************************
  @功能：由 LoRa 任务读取一个待处理字节
  @日期：2026-08-19
  @参数：[输出] byte - 读取到的字节
  @返回值：uint8_t - 1 表示成功，0 表示参数错误或暂无数据
  @线程安全：仅供 LoRa 任务调用
 ******************************************************************************
 */
uint8_t LoraTransport_PopRx(uint8_t *byte);

/**
 ******************************************************************************
  @功能：读取因缓冲区满或串口错误造成的数据丢失累计次数
  @日期：2026-08-19
  @参数：无
  @返回值：uint32_t - 数据丢失事件累计值
 ******************************************************************************
 */
uint32_t LoraTransport_GetDataLossCount(void);

#endif /* LORA_TRANSPORT_H */

/* ===========================================================================
 * 注入一行.js  ——  浏览器控制台里**只粘这一行**即可完成注入
 * ===========================================================================
 *
 * 为什么用它
 * ----------
 *   多行 JS 一旦粘到平台页面上那个 Monaco 代码编辑框, Monaco 只做语法解析、
 *   不解运行, 遇到多行/中文注释块就抛 `Uncaught Error: invalid AST`。
 *   所以别再全文粘贴, 用下面这一行: 它先从本机 8765 端口把 `平台注入.js`
 *   抓回来再执行, 控制台里永远只有一行、语法永远是合法的。
 *
 * 粘的位置(很关键)
 * ------------
 *   F12 → 选 **Console** 标签页 → 看面板**最底下**那一行
 *         **以 `>` 开头的光标输入行**(Chrome 会先提示"不信任这段代码/允许粘贴")
 *   → 光标点在那一行上 → 粘下面这一行 → 回车
 *
 *   ✗ 不要粘到: 平台页面自己的代码编辑框 / Monaco 编辑器 / 任何带语法高亮的代码区
 *   ✗ 不要粘到: DevTools 的 Elements 面板里的 <body> 源码(那是 HTML 树)
 *
 * 端口: 如果 `_live.py 8765` 换了端口, 把下面 8765 一起改掉(两处)。
 * =========================================================================== */

(function(){if(window.__wbLive)return;var s=document.createElement('script');s.src='http://127.0.0.1:8765/inject.js';s.onerror=function(){console.log('[wb-live] 拉不到 http://127.0.0.1:8765/inject.js —— 本机 _live.py 起了吗?');};document.body.appendChild(s);})();


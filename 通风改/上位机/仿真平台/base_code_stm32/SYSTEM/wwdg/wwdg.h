/**
 * @file    wwdg.h
 * @brief   STM32F10x 窗口看门狗（WWDG）驱动接口声明
 *
 * 本头文件提供窗口看门狗（Window Watchdog, WWDG）的初始化与控制接口。
 * WWDG 核心特性：
 * - 计数器从 T[6:0] 递减至 0x3F，若未及时喂狗则触发系统复位；
 * - **喂狗只能在窗口期内进行**：当前计数值必须 ∈ [0x40, W[6:0]]；
 * - 支持提前唤醒中断（EWI）：当计数器递减至 0x40 时触发，提供最后一次喂狗机会；
 * - 时钟源 = PCLK1 / (4096 × 2^fprer)，最低频率约 280 Hz（PCLK1=36MHz, fprer=3）。
 *
 * @note
 * - 一旦使能 WWDG，**无法通过软件关闭**，只能复位停止；
 * - 用户必须实现中断服务函数：void WWDG_IRQHandler(void)；
 * - 典型用法：在 EWI 中断中执行紧急日志记录并重新喂狗。
 *
 * @warning
 * - 参数 tr 必须满足：0x40 ≤ tr ≤ 0x7F；
 * - 窗口值 wr 必须满足：0x40 ≤ wr < tr；
 * - 违反上述约束将导致立即复位或功能异常。
 */
#ifndef __WWDG_H
#define __WWDG_H	    

#include "stm32f10x_wwdg.h"

/* ==============================================================================
 *                              配置常量
 * ============================================================================== */

/**
 * @brief WWDG 默认最大计数值（T[6:0] = 0x7F）
 * @details
 * - 实际有效范围：0x40 ～ 0x7F（低于 0x40 会立即触发复位）；
 * - 此值通常作为初始计数器加载值。
 */
#define WWDG_CNT 0x7f

/* ==============================================================================
 *                            函数声明
 * ============================================================================== */

/**
 * @brief 初始化窗口看门狗（WWDG）
 * @param tr     初始计数值 T[6:0]（建议范围：0x40 ～ 0x7F）
 * @param wr     窗口上限值 W[6:0]（必须满足：0x40 ≤ wr < tr）
 * @param fprer  预分频系数 WDGTB[1:0]（仅低2位有效）：
 *               - 0: 分频 /1  → Fwwdg = PCLK1 / 4096
 *               - 1: 分频 /2  → Fwwdg = PCLK1 / 8192
 *               - 2: 分频 /4  → Fwwdg = PCLK1 / 16384
 *               - 3: 分频 /8  → Fwwdg = PCLK1 / 32768
 * @note
 * - 自动使能 WWDG 时钟、配置 NVIC、开启提前唤醒中断（EWI）；
 * - 调用后 WWDG 立即开始工作，无法关闭。
 */
void WWDG_Init(u8 tr,u8 wr,u32 fprer);

/**
 * @brief 重载 WWDG 计数器（喂狗操作）
 * @param cnt 新的计数值（建议：0x40 ≤ cnt ≤ 0x7F）
 * @details
 * - 此操作必须在 **窗口期** 内调用（即当前计数值 ∈ [0x40, wr]）；
 * - 若在窗口外调用，将立即触发系统复位；
 * - 通常在 WWDG_IRQHandler 中调用以延长超时。
 * @warning 喂狗不是重置，而是写入新计数值，计数器继续递减。
 */
void WWDG_Set_Counter(u8 cnt);

/**
 * @brief 配置 WWDG 提前唤醒中断（EWI）的 NVIC
 * @details
 * - 中断通道：WWDG_IRQn；
 * - 抢占优先级：2，子优先级：3（假设 NVIC 分组为 Group 2）；
 * - 中断在计数器递减至 0x40 时触发，提供最后一次喂狗机会。
 * @note 此函数由 WWDG_Init() 内部调用，一般无需用户直接调用。
 */
void WWDG_NVIC_Init();


#endif // __WWDG_H

 

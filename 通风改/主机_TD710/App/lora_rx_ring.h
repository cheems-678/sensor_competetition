#ifndef LORA_RX_RING_H
#define LORA_RX_RING_H

#include <stdint.h>

#define LORA_RX_RING_SIZE       (256U)
#define LORA_RX_RING_CAPACITY   (LORA_RX_RING_SIZE - 1U)

typedef struct
{
    volatile uint8_t data[LORA_RX_RING_SIZE];
    volatile uint16_t head;
    volatile uint16_t tail;
    volatile uint32_t overflow_count;
} LoRaRxRing;

/**
 ******************************************************************************
  @功能：初始化 LoRa 串口接收环形缓冲区
  @日期：2026-08-19
  @参数：[输出] ring - 环形缓冲区对象
  @返回值：无
  @使用说明：必须在 USART2 接收中断启动前调用
 ******************************************************************************
 */
void LoRaRxRing_Init(LoRaRxRing *ring);

/**
 ******************************************************************************
  @功能：由 USART2 接收中断向环形缓冲区写入一个字节
  @日期：2026-08-19
  @参数：[输入输出] ring - 环形缓冲区对象
         [输入] byte - 接收到的字节
  @返回值：uint8_t - 1 表示写入成功，0 表示参数错误或缓冲区已满
  @线程安全：只允许一个中断生产者调用
 ******************************************************************************
 */
uint8_t LoRaRxRing_PushFromIsr(LoRaRxRing *ring, uint8_t byte);

/**
 ******************************************************************************
  @功能：由 LoRa 任务从环形缓冲区取出一个字节
  @日期：2026-08-19
  @参数：[输入输出] ring - 环形缓冲区对象
         [输出] byte - 取出的字节
  @返回值：uint8_t - 1 表示读取成功，0 表示参数错误或缓冲区为空
  @线程安全：只允许一个任务消费者调用
 ******************************************************************************
 */
uint8_t LoRaRxRing_Pop(LoRaRxRing *ring, uint8_t *byte);

/**
 ******************************************************************************
  @功能：读取环形缓冲区当前待处理字节数
  @日期：2026-08-19
  @参数：[输入] ring - 环形缓冲区对象
  @返回值：uint16_t - 当前待处理字节数，参数为空时返回 0
  @使用说明：返回值是调用瞬间的快照，只用于调度和诊断
 ******************************************************************************
 */
uint16_t LoRaRxRing_Count(const LoRaRxRing *ring);

#endif /* LORA_RX_RING_H */

